#!/usr/bin/env node
// PreToolUse guard (AGENTS.md core rules, §3, §8).
// 1. Blocks edits to generated / protected files.
// 2. Blocks shell commands that skip git hooks, force-push, or retarget the hooks path.
// Exit 2 = block (stderr is shown to Claude); exit 0 = allow.
import { readFileSync } from "node:fs";
import { isAbsolute, relative, resolve } from "node:path";

const PREFIX = "Blocked by .claude/hooks/pre-tool-guard.mjs:";
const ROOT = resolve(process.env.CLAUDE_PROJECT_DIR || process.cwd());
const NEXT_BLOCK_MARKER = /nextjs-agent-[a-z-]+/;

function block(message) {
  process.stderr.write(`${PREFIX} ${message}\n`);
  process.exit(2);
}

function readInput() {
  try {
    return JSON.parse(readFileSync(0, "utf8") || "{}");
  } catch {
    return {};
  }
}

function toRepoPath(filePath) {
  if (!filePath) return null;
  const abs = isAbsolute(filePath) ? filePath : resolve(ROOT, filePath);
  const rel = relative(ROOT, abs).replace(/\\/g, "/");
  if (rel.startsWith("..") || isAbsolute(rel)) return null; // outside the repo
  return rel;
}

function checkFileEdit(toolName, input) {
  const rel = toRepoPath(input.file_path || input.notebook_path);
  if (!rel) return;
  const name = rel.split("/").pop();

  if (rel === "package-lock.json") {
    block(
      "package-lock.json is generated. Change package.json and run `npm install` instead.",
    );
  }
  if (/^\.env(\..+)?$/.test(name) && name !== ".env.example") {
    block(
      `${rel} holds secrets and is never edited by agents. Document the variable in .env.example and ask the user to set the value.`,
    );
  }
  if (rel === "next-env.d.ts") {
    block("next-env.d.ts is generated by Next.js. Leave it alone.");
  }
  if (
    rel === ".cursor/rules/lumira.mdc" ||
    rel === ".github/copilot-instructions.md"
  ) {
    block(
      `${rel} is generated. Edit the core-rules block in AGENTS.md, then run \`npm run rules:sync\`.`,
    );
  }
  if (rel === "AGENTS.md") {
    const edits = [
      input.old_string,
      ...(input.edits || []).map((e) => e.old_string),
    ].filter(Boolean);
    if (edits.some((text) => NEXT_BLOCK_MARKER.test(text))) {
      block(
        "the `nextjs-agent-*` blocks in AGENTS.md are written by `next dev`. Edit outside those markers.",
      );
    }
    if (toolName === "Write") {
      const current = readFileSync(resolve(ROOT, rel), "utf8");
      const wanted =
        current.match(
          /<!-- BEGIN:nextjs-agent-[\s\S]*?END:nextjs-agent-[a-z-]+ -->/g,
        ) || [];
      const content = input.content || "";
      if (wanted.some((blockText) => !content.includes(blockText))) {
        block(
          "rewriting AGENTS.md would change or drop a `nextjs-agent-*` block. Use Edit on the sections outside those markers.",
        );
      }
    }
  }
}

// Split a shell command into simple commands at | ; & && || and newlines,
// respecting quotes, so text inside a commit message is not treated as flags.
function splitCommands(command) {
  const commands = [];
  let tokens = [];
  let token = "";
  let quote = null;
  const pushToken = () => {
    if (token) tokens.push(token);
    token = "";
  };
  const pushCommand = () => {
    pushToken();
    if (tokens.length) commands.push(tokens);
    tokens = [];
  };
  for (let i = 0; i < command.length; i++) {
    const ch = command[i];
    if (quote) {
      if (ch === quote) quote = null;
      else token += ch;
      continue;
    }
    if (ch === '"' || ch === "'") quote = ch;
    else if (ch === " " || ch === "\t") pushToken();
    else if (
      ch === "|" ||
      ch === ";" ||
      ch === "&" ||
      ch === "\n" ||
      ch === "\r"
    )
      pushCommand();
    else token += ch;
  }
  pushCommand();
  return commands;
}

const HOOK_SKIPPING = new Set([
  "commit",
  "push",
  "merge",
  "rebase",
  "cherry-pick",
  "am",
]);

function checkCommand(command) {
  for (const raw of splitCommands(command)) {
    let tokens = raw;

    // Env-var prefixes (bash `HUSKY=0 git …`, PowerShell `$env:HUSKY=0`).
    while (tokens.length && /^[A-Za-z_][A-Za-z0-9_]*=/.test(tokens[0])) {
      if (/^HUSKY=/.test(tokens[0]))
        block("`HUSKY=…` disables git hooks. Run the command without it.");
      tokens = tokens.slice(1);
    }
    if (tokens.some((t) => /^\$env:HUSKY\s*=?/i.test(t)))
      block("setting $env:HUSKY disables git hooks. Don't.");

    const gitAt = tokens.findIndex((t) => /(^|[\\/])git(\.exe)?$/i.test(t));
    if (gitAt === -1) continue;
    const args = tokens.slice(gitAt + 1).filter((t, i, all) => {
      // skip `-C <dir>` / `-c key=value` global options
      const prev = all[i - 1];
      return !(prev === "-C" || prev === "-c") && t !== "-C" && t !== "-c";
    });
    const sub = args[0];
    const rest = args.slice(1);

    if (HOOK_SKIPPING.has(sub) && rest.includes("--no-verify")) {
      block(
        `\`git ${sub} --no-verify\` skips the git hooks. Fix what the hook reports instead (AGENTS.md §8).`,
      );
    }
    if (
      sub === "commit" &&
      rest.some((t) => /^-[a-zA-Z]*n[a-zA-Z]*$/.test(t))
    ) {
      block("`git commit -n` skips the git hooks. Remove -n.");
    }
    if (sub === "push") {
      const forced = rest.some(
        (t) =>
          t === "-f" ||
          /^--force(-with-lease|-if-includes)?(=.*)?$/.test(t) ||
          (/^-[a-zA-Z]+$/.test(t) && t.includes("f")) ||
          t.startsWith("+"),
      );
      if (forced)
        block("force pushes are not allowed. Push normally or ask the user.");
    }
    if (sub === "config" && rest.some((t) => t === "core.hooksPath")) {
      block("core.hooksPath is owned by Husky. Don't change it.");
    }
    if (sub === "reset" && rest.includes("--hard")) {
      block("`git reset --hard` destroys uncommitted work (AGENTS.md §3).");
    }
    if (sub === "clean" && rest.some((t) => /^-[a-zA-Z]*f/.test(t))) {
      block("`git clean -f` deletes untracked work (AGENTS.md §3).");
    }
  }
}

const data = readInput();
const tool = data.tool_name || "";
const input = data.tool_input || {};

if (tool === "Bash" || tool === "PowerShell") checkCommand(input.command || "");
else checkFileEdit(tool, input);

process.exit(0);
